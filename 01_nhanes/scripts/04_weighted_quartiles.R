source(file.path("01_nhanes", "scripts", "00_config.R"), encoding = "UTF-8")
p <- file.path(generated_dir, "nhanes_survey_base_20_59_final_with_flags.rds")
if (!file.exists(p)) stop("Run 03_finalize_analysis_dataset.R first.", call. = FALSE)
d <- readRDS(p)
design <- survey::svydesign(ids=~survey_psu_id, strata=~survey_strata_id, weights=~weight_8yr, data=d, nest=TRUE)
strict_design <- subset(design, core_analysis_eligible_strict)
q <- survey::svyquantile(~LBXBCD, strict_design, quantiles=c(.25,.50,.75), ci=FALSE, na.rm=TRUE)
cutpoints <- as.numeric(q)
expected <- c(.16,.25,.47)
if (any(abs(cutpoints-expected) > 1e-12)) stop("Weighted quartile cutpoints differ from archived values.", call. = FALSE)

d$cd_quartile <- cut(d$LBXBCD, breaks=c(-Inf,cutpoints,Inf), labels=c("Q1","Q2","Q3","Q4"), right=TRUE)
d$cd_quartile <- factor(d$cd_quartile, levels=c("Q1","Q2","Q3","Q4"))
design <- update(design, cd_quartile=d$cd_quartile)
strict_design <- subset(design, core_analysis_eligible_strict)
med <- sapply(levels(d$cd_quartile), function(g) as.numeric(survey::svyquantile(~LBXBCD, subset(strict_design, cd_quartile==g), .5, ci=FALSE, na.rm=TRUE)))
expected_med <- c(Q1=.11,Q2=.20,Q3=.33,Q4=.87)
if (any(abs(med-expected_med) > 1e-12)) stop("Quartile median scores differ from archived values.", call. = FALSE)
score_map <- med; d$cd_quartile_median_score <- unname(score_map[as.character(d$cd_quartile)])
saveRDS(d, file.path(generated_dir,"survey_base_with_quartile_trend_score.rds"),compress="xz")
utils::write.csv(data.frame(quantile=c("25th","50th","75th"),weighted_cutpoint_ug_L=cutpoints),file.path(generated_dir,"weighted_cadmium_quartile_cutpoints.csv"),row.names=FALSE)
utils::write.csv(data.frame(quartile=names(med),weighted_median_cadmium=as.numeric(med)),file.path(generated_dir,"quartile_weighted_median_scores.csv"),row.names=FALSE)
cat("04_weighted_quartiles.R PASS\n")
